const SOCIAL_ORDER = ['twitter_url', 'facebook_url', 'instagram_url', 'youtube_url', 'discord_url'];

const SOCIAL = {
  twitter_url: { Icon: XIcon, label: 'X' },
  facebook_url: { Icon: FacebookIcon, label: 'Facebook' },
  instagram_url: { Icon: InstagramIcon, label: 'Instagram' },
  youtube_url: { Icon: YouTubeIcon, label: 'YouTube' },
  discord_url: { Icon: DiscordIcon, label: 'Discord' },
};

export default function SocialLinks({ settings, className = '' }) {
  const socials = SOCIAL_ORDER.filter((key) => settings?.[key]);
  if (socials.length === 0) return null;

  return (
    <div className={`flex items-center gap-3 ${className}`}>
      {socials.map((key) => {
        const { Icon, label } = SOCIAL[key];
        return (
          <a
            key={key}
            href={settings[key]}
            target="_blank"
            rel="noopener noreferrer"
            className="p-2 rounded-full bg-white/10 hover:bg-white/20 transition-colors"
            title={label}
            aria-label={label}
          >
            <Icon className="w-5 h-5" />
          </a>
        );
      })}
    </div>
  );
}
